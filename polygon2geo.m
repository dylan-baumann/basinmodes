function polygon2geo(poly, char_length, geo_file)
% POLYGON2GEO  Write a straight-sided polygon to a Gmsh .geo script.
%
%   polygon2geo(poly, char_length, geo_file)
%
%   poly         Nx2 array of [x y] vertices (metres), in order around the
%                boundary. The polygon is closed automatically.
%   char_length  Target triangle edge length (metres). Either a scalar
%                (uniform mesh) or an Nx1 vector giving a target size at each
%                vertex, which lets you refine locally (e.g. at a peninsula
%                tip). Gmsh interpolates the size smoothly into the interior.
%   geo_file     Output file name, e.g. 'rectangle.geo'.
%
%   WHY THIS EXISTS (instead of using bdry2geo.m):
%   bdry2geo.m writes Gmsh Spline(...) entries through the boundary points,
%   which is right for smooth coastlines extracted from bathymetry but wrong
%   for a polygon with genuine corners: a spline through corner points rounds
%   the corners off. Here every side is a straight Gmsh Line, so a rectangle
%   stays an exact rectangle.
%
%   The mesh options are written INTO the .geo file so that the file is
%   self-contained (you can also open it directly in the Gmsh GUI):
%     Mesh.Algorithm       = 6   Frontal-Delaunay (same as geo2msh.py)
%     Mesh.MshFileVersion  = 2.2 the format that readmsh.m knows how to parse

    n = size(poly, 1);
    if size(poly, 2) ~= 2 || n < 3
        error('polygon2geo: poly must be an Nx2 array with N >= 3.');
    end
    if isscalar(char_length)
        char_length = char_length * ones(n, 1);
    end
    char_length = char_length(:);
    if numel(char_length) ~= n
        error('polygon2geo: char_length must be a scalar or have one entry per vertex.');
    end

    fid = fopen(geo_file, 'w');
    if fid == -1
        error('polygon2geo: could not open "%s" for writing.', geo_file);
    end
    cleanup = onCleanup(@() fclose(fid));

    fprintf(fid, '// Generated by polygon2geo.m -- straight-sided polygon.\n');
    fprintf(fid, 'Mesh.Algorithm = 6;\n');
    fprintf(fid, 'Mesh.MshFileVersion = 2.2;\n\n');

    % --- Points (z = 0: this is a 2D problem) ---
    for j = 1:n
        fprintf(fid, 'Point(%d) = {%.12g, %.12g, 0, %.12g};\n', ...
                j, poly(j,1), poly(j,2), char_length(j));
    end

    % --- Straight lines joining consecutive points (last one closes the loop) ---
    for j = 1:n
        fprintf(fid, 'Line(%d) = {%d, %d};\n', j, j, mod(j, n) + 1);
    end

    % --- One closed loop and the plane surface it bounds ---
    ids = sprintf('%d,', 1:n);
    ids = ids(1:end-1);                      % drop trailing comma
    fprintf(fid, 'Line Loop(%d) = {%s};\n', n + 1, ids);
    fprintf(fid, 'Plane Surface(%d) = {%d};\n', n + 2, n + 1);
end
